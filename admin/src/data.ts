export const cashOlderThan = (confirmedOn: string, hours: number): boolean => {
  const confirmed = new Date(`${confirmedOn}T12:00:00+03:00`).getTime();
  const now = new Date(`${TODAY}T18:00:00+03:00`).getTime();
  return now - confirmed > hours * 60 * 60 * 1000;
};
